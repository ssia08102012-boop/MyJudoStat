type TranslationKeys = keyof (typeof TR)['uk']

let currentLang: Lang = (localStorage.getItem('judo_lang') as Lang) || 'uk'

export function getLang(): Lang {
  return currentLang
}

export function setLang(lang: Lang): void {
  currentLang = lang
  localStorage.setItem('judo_lang', lang)
}

export function t(key: TranslationKeys): string {
  const dict = TR[currentLang] ?? TR.uk
  return (dict as Record<string, string>)[key] ?? (TR.uk as Record<string, string>)[key] ?? key
}

const BELT_KEY_MAP: Partial<Record<string, TranslationKeys>> = {
  white: 'belt_white',
  yellow: 'belt_yellow',
  orange: 'belt_orange',
  green: 'belt_green',
  blue: 'belt_blue',
  brown: 'belt_brown',
  black1: 'belt_black1',
  black2: 'belt_black2',
  black3: 'belt_black3',
}

// Legacy mapping for Ukrainian values stored before i18n migration
const LEGACY_BELT_MAP: Record<string, string> = {
  'білий': 'white', 'жовтий': 'yellow', 'помаранчевий': 'orange',
  'зелений': 'green', 'синій': 'blue', 'коричневий': 'brown',
  'чорний 1 дан': 'black1', 'чорний 2 дан': 'black2', 'чорний 3 дан': 'black3',
}

export function tBelt(key: string | undefined): string {
  if (!key) return '—'
  const tKey = BELT_KEY_MAP[key] ?? BELT_KEY_MAP[LEGACY_BELT_MAP[key.toLowerCase()]]
  return tKey ? t(tKey) : key
}
